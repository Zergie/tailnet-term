fn command_help(command: &str) -> Option<(&'static str, std::ops::RangeInclusive<usize>)> {
    match command {
        "keygen" => Some((KEYGEN_HELP, 1..=1)),
        "ephemeral-key" => Some((EPHEMERAL_KEY_HELP, 0..=usize::MAX)),
        "server" => Some((SERVER_HELP, 3..=4)),
        "client" => Some((CLIENT_HELP, 2..=usize::MAX)),
        "ip" => Some((IP_HELP, 0..=0)),
        _ => None,
    }
}

fn is_help(arg: &str) -> bool {
    matches!(arg, "-h" | "--help")
}

fn main() -> std::process::ExitCode {
    match run() {
        Ok(()) => std::process::ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("Error: {error}");
            std::process::ExitCode::FAILURE
        }
    }
}

fn run() -> Result<(), Box<dyn Error>> {
    let mut args = std::env::args().skip(1).peekable();
    let command = args.next();
    match command.as_deref() {
        None | Some("-h" | "--help") => {
            println!("{HELP}");
            return Ok(());
        }
        Some("help") => {
            match args.next().as_deref() {
                None => println!("{HELP}"),
                Some(name) => {
                    let (help, _) = command_help(name).ok_or_else(|| {
                        format!("unknown command '{name}'. Run tailnet-term.exe --help.")
                    })?;
                    println!("{help}");
                }
            }
            return Ok(());
        }
        Some(name) => {
            if let Some((help, count)) = command_help(name) {
                if args.peek().is_some_and(|arg| is_help(arg)) {
                    println!("{help}");
                    return Ok(());
                }
                if !count.contains(&args.len()) {
                    return Err(format!(
                        "invalid argument count for '{name}'. Run tailnet-term.exe {name} --help."
                    )
                    .into());
                }
            }
        }
    }
    match command.as_deref() {
        #[cfg(feature = "classic-pty")]
        Some("classic-console-child") => Ok(terminal::classic::run(
            args.next().ok_or("missing shell executable")?.as_ref(),
        )?),
        Some("console-child") => Ok(terminal::conpty::supervise_console(
            args.next()
                .ok_or("missing console interrupt handle")?
                .parse()?,
            args.next().ok_or("missing PowerShell executable")?.as_ref(),
        )?),
        Some("ephemeral-key") => ephemeral_key::create(args.collect()),
        Some("keygen") => terminal::auth::keygen(
            args.next()
                .ok_or("keygen requires a private key path")?
                .as_ref(),
        ),
        Some("server") => {
            let peer = args
                .next()
                .ok_or("server requires the permitted client Tailnet IPv4 address")?
                .parse()?;
            let key = terminal::auth::parse_key(
                &args
                    .next()
                    .ok_or("server requires the client's public key")?,
            )?;
            let program = args
                .next()
                .ok_or("server requires the path to PowerShell")?
                .into();
            let state = args
                .next()
                .unwrap_or_else(|| "terminal-tailnet-state.bin".to_owned())
                .into();
            echo::run_terminal(peer, key, program, state)
        }
        Some("client") => {
            let peer = args
                .next()
                .ok_or("client requires the server's Tailnet IPv4 address")?
                .parse()?;
            let key = args
                .next()
                .ok_or("client requires the private key file path")?;
            let command: Vec<String> = args.collect();
            let command = (!command.is_empty()).then(|| command.join(" "));
            let code = match terminal::client::run(peer, key.as_ref(), command) {
                Ok(code) => code,
                Err(error) => {
                    eprintln!("Error: {error}");
                    terminal::client::CONNECTION_LOST
                }
            };
            std::io::Write::flush(&mut std::io::stdout())?;
            // Windows exit codes are u32; `ExitCode` only carries a u8.
            std::process::exit(code as i32)
        }
        Some("ip") => local_ip::run(),
        #[cfg(feature = "diagnostics")]
        Some("pty-check") => {
            let program = args.next().ok_or("pty-check requires a PowerShell path")?;
            terminal::pty::probe(&std::path::absolute(program)?)
        }
        #[cfg(feature = "diagnostics")]
        Some("control") => control_probe(),
        #[cfg(feature = "diagnostics")]
        Some("relay") => echo::relay_probe(&args.next().ok_or("relay requires a DERP hostname")?),
        Some(name) => Err(format!("unknown command '{name}'. Run tailnet-term.exe --help.").into()),
        None => unreachable!("handled above"),
    }
}

fn connect(port: u16) -> std::io::Result<TcpStream> {
    let timeout = Duration::from_secs(8);
    // Bound the whole connect: the server retries control from its packet loop.
    let deadline = std::time::Instant::now() + timeout;
    let mut last_error = None;
    let mut connected = None;
    for address in (CONTROL_HOST, port).to_socket_addrs()? {
        let remaining = deadline.saturating_duration_since(std::time::Instant::now());
        if remaining.is_zero() {
            break;
        }
        match TcpStream::connect_timeout(&address, remaining) {
            Ok(stream) => {
                connected = Some(stream);
                break;
            }
            Err(error) => last_error = Some(error),
        }
    }
    let stream = connected.ok_or_else(|| {
        last_error.unwrap_or_else(|| {
            std::io::Error::new(std::io::ErrorKind::TimedOut, "no reachable control address")
        })
    })?;
    let timeout = Some(timeout);
    stream.set_read_timeout(timeout)?;
    stream.set_write_timeout(timeout)?;
    Ok(stream)
}

fn control_key() -> Result<[u8; 32], Box<dyn Error>> {
    let mut tls = tls_stream(CONTROL_HOST, connect(443)?)?;
    write!(
        tls,
        "GET /key?v=130 HTTP/1.0\r\nHost: {CONTROL_HOST}\r\nConnection: close\r\n\r\n"
    )?;
    let mut response = Vec::new();
    tls.take(16 * 1024).read_to_end(&mut response)?;
    let end = response
        .windows(4)
        .position(|bytes| bytes == b"\r\n\r\n")
        .ok_or("missing HTTP headers")?;
    if !response.starts_with(b"HTTP/1.0 200 ") && !response.starts_with(b"HTTP/1.1 200 ") {
        return Err("control key endpoint did not return HTTP 200".into());
    }
    let body: serde_json::Value = serde_json::from_slice(&response[end + 4..])?;
    let hex = body["publicKey"]
        .as_str()
        .and_then(|value| value.strip_prefix("mkey:"))
        .ok_or("missing control key")?;
    if hex.len() != 64 || !hex.as_bytes().iter().all(u8::is_ascii_hexdigit) {
        return Err("invalid control key encoding".into());
    }
    let mut key = [0; 32];
    for (index, byte) in key.iter_mut().enumerate() {
        *byte = u8::from_str_radix(&hex[2 * index..2 * index + 2], 16)?;
    }
    Ok(key)
}

fn tls_stream(
    host: &str,
    socket: TcpStream,
) -> Result<StreamOwned<ClientConnection, TcpStream>, Box<dyn Error>> {
    let mut roots = RootCertStore::empty();
    roots.add_parsable_certificates(rustls_native_certs::load_native_certs().certs);
    let mut tls = ClientConfig::builder()
        .with_root_certificates(roots)
        .with_no_client_auth();
    tls.alpn_protocols = vec![b"http/1.1".to_vec()];
    let connection = ClientConnection::new(Arc::new(tls), host.to_owned().try_into()?)?;
    Ok(StreamOwned::new(connection, socket))
}

struct ControlStream(TcpStream);

impl Duplex for ControlStream {
    fn read(&mut self, buf: &mut [u8]) -> Result<usize, ()> {
        self.0.read(buf).map_err(|_| ())
    }

    fn write_all(&mut self, buf: &[u8]) -> Result<(), ()> {
        self.0.write_all(buf).map_err(|_| ())
    }
}

#[cfg(feature = "diagnostics")]
fn control_probe() -> Result<(), Box<dyn Error>> {
    let mut machine_key = [0; 32];
    getrandom::getrandom(&mut machine_key).map_err(|err| err.to_string())?;
    open_control(&machine_key)?;
    println!("PASS: HTTPS control-key lookup, Noise handshake and HTTP/2 setup");
    Ok(())
}

fn open_control(machine_key: &[u8; 32]) -> Result<Http2Client, Box<dyn Error>> {
    let (handshake, initial_frame) =
        control_cipher::begin_handshake(machine_key, &control_key()?).map_err(|err| err.to_string())?;
    let header = control_link::base64_encode(&initial_frame);
    let mut stream = control_link::negotiate_upgrade(
        Box::new(ControlStream(connect(80)?)),
        CONTROL_HOST,
        &header,
    )
    .map_err(|err| err.to_string())?;
    let (kind, response) = stream.read_record().map_err(|err| err.to_string())?;
    if kind != control_cipher::RECORD_RESPONSE {
        return Err(format!("unexpected control reply {kind}").into());
    }
    let encrypted = handshake
        .finish(&response)
        .map_err(|err| err.to_string())?;
    let (session, _) =
        Http2Client::establish(stream, encrypted, CONTROL_HOST.to_owned()).map_err(|err| err.to_string())?;
    Ok(session)
}
